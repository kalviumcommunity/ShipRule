class QueryRequest(BaseModel):
    """Input payload for RAG query requests with strict length validation."""
    question: str = Field(
        ...,
        min_length=3,
        max_length=1000,
        description="The question to be answered by the RAG system."
    )
    use_reranking: Optional[bool] = Field(
        default=True,
        description="Enable cross-encoder re-ranking stage."
    )
    final_k: Optional[int] = Field(
        default=3,
        ge=1,
        le=10,
        description="Number of Top-K context chunks to retrieve."
    )

    model_config = {
        "json_schema_extra": {
            "example": {
                "question": "What shipping documentation is required for international customs clearance?",
                "use_reranking": True,
                "final_k": 3
            }
        }
    }


class Source(BaseModel):
    """Source reference detail backing a RAG answer claim."""
    source: str = Field(..., description="Document source filename.")
    chunk_id: Optional[str] = Field(default=None, description="Unique chunk or document identifier.")
    score: Optional[float] = Field(default=None, description="Retrieval similarity or re-rank score.")


class QueryResponse(BaseModel):
    """Structured JSON response returned to frontend or client applications."""
    answer: str = Field(..., description="Grounded answer text generated by RAG system.")
    sources: List[Source] = Field(default_factory=list, description="List of cited source documents.")
    status: str = Field(..., description="Status code: 'answered', 'refused', or 'error'.")
    metadata: Optional[Dict[str, Any]] = Field(default=None, description="Timing and token usage metadata.")

    model_config = {
        "json_schema_extra": {
            "example": {
                "answer": "International shipments require a commercial invoice and packing list [Source: shipping_rules.txt].",
                "sources": [
                    {
                        "source": "shipping_rules.txt",
                        "chunk_id": "shipping_rules.txt:1",
                        "score": 0.84
                    }
                ],
                "status": "answered",
                "metadata": {
                    "token_usage": {"input_tokens": 420, "output_tokens": 45, "total_tokens": 465},
                    "timing_ms": 1250.5
                }
            }
        }
    }


class IndexingSummary(BaseModel):
    """Structured indexing summary for an uploaded document."""
    document: str = Field(..., description="Stored document path relative to uploads directory.")
    chunks: int = Field(..., description="Number of text chunks generated from the document.")
    indexed: int = Field(..., description="Number of vector embeddings successfully indexed.")

    model_config = {
        "json_schema_extra": {
            "example": {
                "document": "uploads/new-policy.md",
                "chunks": 12,
                "indexed": 12
            }
        }
    }


class DocumentUploadResponse(BaseModel):
    """Response model returned following successful document upload and indexing."""
    status: str = Field(default="indexed", description="Indexing status result.")
    filename: str = Field(..., description="Original name of the uploaded document file.")
    summary: IndexingSummary = Field(..., description="Detailed indexing metrics summary.")

    model_config = {
        "json_schema_extra": {
            "example": {
                "status": "indexed",
                "filename": "new-policy.md",
                "summary": {
                    "document": "uploads/new-policy.md",
                    "chunks": 12,
                    "indexed": 12
                }
            }
        }
    }


