@app.post("/query", response_model=QueryResponse, tags=["RAG Pipeline"])
def query_rag(request: QueryRequest):
    """
    Query endpoint that accepts a user question, runs the RAG pipeline,
    and returns a grounded answer with structured source citations.
    """
    logger.info(f"Received API query request: {request.question}")

    # Validate input parameter bounds
    if not request.question or not request.question.strip():
        raise HTTPException(
            status_code=http_status.HTTP_400_BAD_REQUEST,
            detail="Question field cannot be empty or whitespace only."
        )

    try:
        pipeline_result = answer_query(
            query=request.question.strip(),
            final_k=request.final_k or 3,
            use_reranking=request.use_reranking if request.use_reranking is not None else True
        )
    except ValueError as val_err:
        logger.warning(f"Invalid input parameter error: {val_err}")
        raise HTTPException(
            status_code=http_status.HTTP_400_BAD_REQUEST,
            detail=str(val_err)
        )
    except Exception as exc:
        logger.error(f"RAG pipeline execution failed: {exc}", exc_info=True)
        raise HTTPException(
            status_code=http_status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="RAG service failed"
        )

    answer_text = pipeline_result.get("answer", "")
    retrieved_chunks = pipeline_result.get("retrieved_chunks", [])
    guardrail_decision = pipeline_result.get("guardrail_decision", "ALLOW")

    # Format sources list
    sources_list: List[Source] = []
    seen_sources = set()

    for chunk in retrieved_chunks:
        src_name = chunk.get("source", "unknown")
        chunk_idx = chunk.get("chunk_index", 1)
        chunk_id = chunk.get("document_id") or f"{src_name}:{chunk_idx}"
        score = chunk.get("rerank_score", chunk.get("similarity_score", 0.0))

        if chunk_id not in seen_sources:
            seen_sources.add(chunk_id)
            sources_list.append(Source(
                source=src_name,
                chunk_id=chunk_id,
                score=round(float(score), 4) if score is not None else None
            ))

    # Determine status
    if "insufficient" in answer_text.lower() or "cannot answer" in answer_text.lower() or guardrail_decision == "REFUSE":
        status_str = "refused"
    else:
        status_str = "answered"

    metadata_dict = {
        "token_usage": pipeline_result.get("token_usage", {}),
        "timing": pipeline_result.get("timing", {}),
        "guardrail_decision": guardrail_decision
    }

    return QueryResponse(
        answer=answer_text,
        sources=sources_list,
        status=status_str,
        metadata=metadata_dict
    )


@app.post(
    "/documents",
    response_model=DocumentUploadResponse,
    status_code=http_status.HTTP_200_OK,
    tags=["Document Management"]
)
async def upload_document(file: UploadFile = File(...)):
    """
    Uploads, validates, cleans, chunks, embeds, and indexes a .txt, .md, or .pdf document.
    Makes the uploaded document immediately searchable through the /query endpoint.
    """
    logger.info(f"Received document upload request for filename: {getattr(file, 'filename', None)}")

    # 1. Filename presence validation
    if not file or not file.filename or not file.filename.strip():
        raise HTTPException(
            status_code=http_status.HTTP_400_BAD_REQUEST,
            detail="Missing or invalid filename"
        )

    raw_filename = file.filename.strip()

    # 2. Extension validation
    ext = Path(raw_filename).suffix.lower()
    if ext not in SUPPORTED_EXTENSIONS:
        raise HTTPException(
            status_code=http_status.HTTP_415_UNSUPPORTED_MEDIA_TYPE,
            detail="Unsupported file type"
        )

    # 3. Path traversal & filename sanitization
    original_filename = Path(raw_filename).name
    if not original_filename or original_filename in (".", ".."):
        raise HTTPException(
            status_code=http_status.HTTP_400_BAD_REQUEST,
            detail="Missing or invalid filename"
        )

    # 4. Read & Size Validation
    try:
        content = await file.read()
    except Exception as exc:
        logger.error(f"Failed to read upload file stream: {exc}")
        raise HTTPException(
            status_code=http_status.HTTP_400_BAD_REQUEST,
            detail="Failed to read uploaded file"
        )

    if len(content) == 0:
        raise HTTPException(
            status_code=http_status.HTTP_400_BAD_REQUEST,
            detail="Document contains no extractable text"
        )

    if len(content) > MAX_UPLOAD_SIZE_MB * 1024 * 1024:
        raise HTTPException(
            status_code=http_status.HTTP_413_REQUEST_ENTITY_TOO_LARGE,
            detail=f"File exceeds maximum allowed upload size of {MAX_UPLOAD_SIZE_MB}MB"
        )

    # 5. Secure File Storage under uploads/
    uploads_dir = Path(project_root) / "uploads"
    uploads_dir.mkdir(parents=True, exist_ok=True)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    unique_id = uuid.uuid4().hex[:8]
    sanitized_basename = re.sub(r"[^\w\.-]", "_", original_filename)
    stored_filename = f"{timestamp}_{unique_id}_{sanitized_basename}"
    stored_filepath = (uploads_dir / stored_filename).resolve()

    # Verify path safety to prevent path traversal outside uploads/
    if not str(stored_filepath).startswith(str(uploads_dir.resolve())):
        raise HTTPException(
            status_code=http_status.HTTP_400_BAD_REQUEST,
            detail="Unsafe filename or path traversal attempt"
        )

    try:
        stored_filepath.write_bytes(content)
    except Exception as exc:
        logger.error(f"Failed to write stored upload file: {exc}")
        raise HTTPException(
            status_code=http_status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Document indexing failed"
        )

    # 6. Processing Pipeline & Indexing
    try:
        summary_result = process_uploaded_document(stored_filepath, original_filename)
    except ValueError as val_err:
        logger.warning(f"Document extraction validation error: {val_err}")
        raise HTTPException(
            status_code=http_status.HTTP_400_BAD_REQUEST,
            detail=str(val_err)
        )
    except HTTPException:
        raise
    except Exception as exc:
        logger.error(f"Document processing or indexing failed: {exc}", exc_info=True)
        raise HTTPException(
            status_code=http_status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Document indexing failed"
        )

    return DocumentUploadResponse(
        status="indexed",
        filename=original_filename,
        summary=IndexingSummary(
            document=summary_result["document"],
            chunks=summary_result["chunks"],
            indexed=summary_result["indexed"]
        )
    )

